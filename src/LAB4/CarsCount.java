package LAB4;

public class CarsCount {
    private int nrElectricCars;
    private int nrGasCars;
    private int nrCarsWithPeople;
    private int nrCarsWithRobots;
    private int nrCarsDined;
    private int nrCarsNotDined;
    private int consumptionElectricCars;
    private int consumtionGasCars;

    public void setNrElectricCars(int nrElectricCars) {
        this.nrElectricCars = nrElectricCars;
    }

    public int getNrElectricCars() {
        return nrElectricCars;
    }

    public void setNrGasCars(int nrGasCars) {
        this.nrGasCars = nrGasCars;
    }

    public int getNrGasCars() {
        return nrGasCars;
    }

    public void setNrCarsWithPeople(int nrCarsWithPeople) {
        this.nrCarsWithPeople = nrCarsWithPeople;
    }

    public int getNrCarsWithPeople() {
        return nrCarsWithPeople;
    }

    public void setNrCarsWithRobots(int nrCarsWithRobots) {
        this.nrCarsWithRobots = nrCarsWithRobots;
    }

    public int getNrCarsWithRobots() {
        return nrCarsWithRobots;
    }

    public void setNrCarsDined(int nrCarsDined) {
        this.nrCarsDined = nrCarsDined;
    }

    public int getNrCarsDined() {
        return nrCarsDined;
    }

    public void setNrCarsNotDined(int nrCarsNotDined) {
        this.nrCarsNotDined = nrCarsNotDined;
    }

    public int getNrCarsNotDined() {
        return nrCarsNotDined;
    }

    public void setConsumptionElectricCars(int consumptionElectricCars) {
        this.consumptionElectricCars = consumptionElectricCars;
    }

    public int getConsumptionElectricCars() {
        return consumptionElectricCars;
    }

    public void setConsumtionGasCars(int consumtionGasCars) {
        this.consumtionGasCars = consumtionGasCars;
    }

    public int getConsumtionGasCars() {
        return consumtionGasCars;
    }
}
